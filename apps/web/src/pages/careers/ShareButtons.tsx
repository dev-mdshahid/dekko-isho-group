export function ShareButtons({ slug, title }: { slug: string; title: string }) {
  const url = shareUrl(slug)
  const [copied, setCopied] = useState(false)

  useEffect(() => {
    if (!copied) return
    const t = window.setTimeout(() => setCopied(false), 2000)
    return () => window.clearTimeout(t)
  }, [copied])

  async function copy() {
    try {
      await navigator.clipboard.writeText(url)
    } catch {
      const input = document.createElement('input')
      input.value = url
      document.body.appendChild(input)
      input.select()
      document.execCommand('copy')
      input.remove()
    }
    setCopied(true)
  }

  const text = `${title} at Dekko ISHO Group`
  const links = [
    { label: 'LinkedIn', href: `https://www.linkedin.com/sharing/share-offsite/?url=${encodeURIComponent(url)}`, icon: <LinkedInIcon /> },
    { label: 'WhatsApp', href: `https://wa.me/?text=${encodeURIComponent(`${text} ${url}`)}`, icon: <WhatsAppIcon /> },
    { label: 'Facebook', href: `https://www.facebook.com/sharer/sharer.php?u=${encodeURIComponent(url)}`, icon: <FacebookIcon /> },
  ]

  return (
    <div className="careers-share">
      <span className="careers-share-label">Share this role</span>
      <div className="careers-share-buttons">
        <button type="button" className="careers-share-button" onClick={copy} aria-label={copied ? 'Link copied' : 'Copy link'}>
          {copied ? <Check size={16} aria-hidden="true" /> : <Link2 size={16} aria-hidden="true" />}
        </button>
        {links.map((l) => (
          <a
            key={l.label}
            href={l.href}
            className="careers-share-button"
            target="_blank"
            rel="noopener noreferrer"
            aria-label={`Share on ${l.label}`}
          >
            {l.icon}
          </a>
        ))}
        <span className="careers-share-feedback" role="status" aria-live="polite">
          {copied ? 'Link copied' : ''}
        </span>
      </div>
    </div>
  )
}
